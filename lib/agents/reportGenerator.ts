import { FullAegisInvestigation } from "../types/agent";

export function generatePoliceDossier(inv: FullAegisInvestigation): string {
  return `================================================================================
OFFICIAL INCIDENT INVESTIGATION REPORT // NATIONAL CYBERCRIME REPORTING PORTAL
GENERATED BY: AEGIS OMEGA - AGENTIC FRAUD INTELLIGENCE PLATFORM
EVIDENCE IDENTIFIER: ${inv.forensics.evidenceId}
INGESTION TIMESTAMP (UTC): ${inv.timestamp}
================================================================================

1. INCIDENT CLASSIFICATION & STATUTORY VIOLATIONS:
--------------------------------------------------------------------------------
* Classification: ${inv.scamDna.fingerprint.primaryVector} (${inv.scamDna.fingerprint.clusterCategory})
* Assessed Risk Score: ${inv.riskIntelligence.finalScore}/100 [${inv.riskIntelligence.riskLevel}]
* Statutorily Implicated Acts:
  - Section 66D, Information Technology Act, 2000 (Cheating by personation by using computer resource)
  - Section 318(4), Bharatiya Nyaya Sanhita (BNS) / Section 420, IPC (Cheating and dishonestly inducing delivery of property)
  - Section 66C, Information Technology Act, 2000 (Identity theft)

2. PERPETRATOR INFRASTRUCTURE TELEMETRY:
--------------------------------------------------------------------------------
* Claimed Organization: ${inv.trustVerification.claimedOrganization}
* Verified Official Domain: ${inv.trustVerification.officialDomain || "None"}
* Suspect Host / Domain: ${inv.indicators.domains.join(", ") || "None"}
* Contact / Phone Vectors: ${inv.indicators.phoneNumbers.join(", ") || "None"}
* Financial / UPI Handles: ${inv.indicators.upiHandles.join(", ") || "None"}
* Hosting Infrastructure ASN: ${inv.threatIntelligence.asnInfo}
* Origin Server Location: ${inv.threatIntelligence.infrastructureLocation.city}, ${inv.threatIntelligence.infrastructureLocation.country}

3. PREDICTIVE ATTACK CHAIN & DOWNSTREAM VULNERABILITY:
--------------------------------------------------------------------------------
${inv.futureAttackSimulation.stages.map(s => `[Stage ${s.stageNumber} - ${s.status}] ${s.stageName}\n  Description: ${s.description}\n  Evidence: ${s.evidence}`).join("\n\n")}

4. SOCIAL ENGINEERING EXPLOITATION ANALYSIS:
--------------------------------------------------------------------------------
${inv.psychology.detectedTactics.map(t => `* Vector: ${t.category} [${t.severity}]\n  Extracted Text: "${t.highlightedPhrase}"\n  Analysis: ${t.explanation}`).join("\n")}

5. CRYPTOGRAPHIC CHAIN OF CUSTODY:
--------------------------------------------------------------------------------
* Original Message SHA-256 Digest:
  ${inv.forensics.originalPayloadSha256}
* Normalized Message SHA-256 Digest:
  ${inv.forensics.normalizedPayloadSha256}
* Forensic Disclaimer: ${inv.forensics.integrityDisclaimer}

6. RECOMMENDED LAW ENFORCEMENT INTERVENTION:
--------------------------------------------------------------------------------
1. Issue urgent preservation notice under Section 91 CrPC to telecommunications provider for sender MSISDN.
2. Request immediate DNS domain takedown with respective registrar.
3. Flag implicated UPI handles and beneficiary bank accounts across the National Cybercrime Reporting Portal (1930 / I4C).
================================================================================`;
}

export function generateStixBundle(inv: FullAegisInvestigation) {
  return {
    type: "bundle",
    id: `bundle--${inv.investigationId}`,
    spec_version: "2.1",
    objects: [
      {
        type: "indicator",
        id: `indicator--${inv.forensics.evidenceId.toLowerCase()}`,
        created: inv.timestamp,
        modified: inv.timestamp,
        name: inv.scamDna.fingerprint.primaryVector,
        description: inv.futureAttackSimulation.simulationSummary,
        pattern_type: "stix",
        pattern: `[domain-name:value = '${inv.indicators.domains[0] || "unknown.com"}']`,
        valid_from: inv.timestamp,
        confidence: inv.riskIntelligence.finalScore,
      },
      {
        type: "threat-actor",
        id: `threat-actor--${inv.scamDna.fingerprint.fingerprintId.toLowerCase()}`,
        created: inv.timestamp,
        modified: inv.timestamp,
        name: `Unidentified Actor (${inv.scamDna.fingerprint.clusterCategory})`,
        threat_actor_types: ["cybercriminal"],
        sophistication: "intermediate",
        resource_level: "individual",
        primary_motivation: "personal-gain",
      }
    ]
  };
}
